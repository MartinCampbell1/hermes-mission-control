export type TranslationKey = keyof typeof en;

const resources: Record<Locale, Record<TranslationKey, string>> = { en, ru };

function normalizeLocale(value: string | null): Locale {
  return value === 'en' || value === 'ru' ? value : 'ru';
}

export function translate(
  locale: Locale,
  key: TranslationKey,
  values: Record<string, string | number> = {}
): string {
  const template = resources[locale][key] ?? resources.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : `{${name}}`
  );
}

interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, values?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export const localeLabels: Record<Locale, string> = {
  ru: ru['locale.ru'],
  en: en['locale.en'],
};

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() =>
    normalizeLocale(localStorage.getItem(STORAGE_KEY))
  );

  const setLocale = useCallback((next: Locale) => {
    localStorage.setItem(STORAGE_KEY, next);
    setLocaleState(next);
  }, []);

  const t = useCallback(
    (key: TranslationKey, values?: Record<string, string | number>) =>
      translate(locale, key, values),
    [locale]
  );

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used within I18nProvider');
  return value;
}
